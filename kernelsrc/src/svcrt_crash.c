const char *svcrt_crash_reason_name(uint32 reason)
{
    switch(reason)
    {
        case SVCRT_CRASH_REASON_NONE:      return "none";
        case SVCRT_CRASH_REASON_FAULT:     return "crash-limit";
        case SVCRT_CRASH_REASON_HEARTBEAT: return "heartbeat";
        case SVCRT_CRASH_REASON_AUDIT:     return "audit";
        default:                           return "unknown";
    }
}

