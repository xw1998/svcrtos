void svcrt_crash_init(void)
{
    svcrt_crash_journal_t *p_j = &svcrt_crash_journal;
    uint32 i;

    if(svcrt_crash_valid() != 0)
    {
        /* A journal from an earlier run survived the reset. Keeping it is the
         * entire point of the noinit region, so the only thing to do here is
         * note that another boot happened. */
        p_j->boots++;
        svcrt_crash_commit();
        return;
    }

    /* Never written, half written, or written by an older layout: not
     * evidence. Starting clean costs one extra crash before an image is
     * disabled; reading garbage as history could disable an image that never
     * faulted, which is the worse of the two mistakes. */
    for(i = 0u; i < (uint32)SVCRT_SLOT_ARRAY_MAX; i++)
    {
        svcrt_crash_clear_entry(i);
    }

    /* The MiniApp table is part of the same record: a journal rebuilt from
     * scratch has to start with it empty too, or leftover RAM bytes would be
     * read as "these paths already crashed N times". */
    for(i = 0u; i < (uint32)SVCRT_CRASH_MINI_MAX; i++)
    {
        svcrt_crash_clear_mini(i);
    }

    p_j->magic   = (uint32)SVCRT_CRASH_MAGIC;
    p_j->version = (uint32)SVCRT_CRASH_VERSION;
    p_j->seq     = 0u;
    p_j->boots   = 1u;
    svcrt_crash_commit();
}

void svcrt_crash_scan_apply(void)
{
    svcrt_partition_table_t *p_pt = svcrt_ptable_get();
    svcrt_crash_journal_t *p_j = &svcrt_crash_journal;
    uint32 limit = svcrt_crash_limit();
    uint32 changed = 0u;
    uint32 i;

    for(i = 0u; (i < p_pt->slot_max) && (i < (uint32)SVCRT_SLOT_ARRAY_MAX); i++)
    {
        if(p_pt->slot_type[i] == SVCRT_SLOT_FREE)
        {
            /* No image in this record: any entry left over from an uninstall
             * must not be waiting to charge the next occupant. */
            if((p_j->base[i] != 0u) || (p_j->crash_cnt[i] != 0u) ||
               (p_j->dis_reason[i] != SVCRT_CRASH_REASON_NONE))
            {
                svcrt_crash_clear_entry(i);
                changed = 1u;
            }
            continue;
        }

        if((p_pt->slot_base[i] == 0u) || (p_j->base[i] != p_pt->slot_base[i]))
        {
            /* The entry describes a different image - replaced, moved by
             * compaction, or the record was reused. Drop it rather than charge
             * a newcomer with someone else's crashes. */
            svcrt_crash_clear_entry(i);
            changed = 1u;
        }

        /* Re-tag unconditionally: from here on the entry belongs to the image
         * the scan just found, whatever it replaced. */
        p_j->base[i] = p_pt->slot_base[i];
        changed = 1u;

        p_pt->slot_crash_cnt[i] = p_j->crash_cnt[i];

        /* Two ways a slot can already be past the limit at boot:
         *   - it was disabled in a previous run and the journal survived;
         *   - it was counted by the guard just before it starved the watchdog,
         *     so the reset landed before the normal terminal path could run.
         * Both mean "this slot must not run again on its own". */
        if((p_j->dis_reason[i] != SVCRT_CRASH_REASON_NONE) ||
           ((limit != 0u) && (p_j->crash_cnt[i] >= limit)))
        {
            if(p_j->dis_reason[i] == SVCRT_CRASH_REASON_NONE)
            {
                p_j->dis_reason[i] = (p_j->last_reason[i] != SVCRT_CRASH_REASON_NONE)
                                   ? p_j->last_reason[i]
                                   : (uint32)SVCRT_CRASH_REASON_FAULT;
                p_j->dis_tick[i] = 0u;      /* disabled before this boot began */
                changed = 1u;
            }

            /* Keep the image out of this boot's autostart, and keep the state
             * the operator saw before the reset. INVALID is what "present, but
             * the kernel refuses to run it" looks like, so 'app list' cannot
             * be read as "the slot came back empty". */
            p_pt->slot_autostart[i] = 0u;
            (void)svcrt_ptable_set_slot(i, SVCRT_APP_SLOT_INVALID,
                                        p_pt->slot_entry[i], 0u);

            SVCRT_LOGE("CRASH", "slot %u held: %s, %u faults, last at tick %u"
                       " (retry with 'app start %u' or 'drv start %u')",
                       (unsigned)i,
                       svcrt_crash_reason_name(p_j->dis_reason[i]),
                       (unsigned)p_j->crash_cnt[i],
                       (unsigned)p_j->dis_tick[i],
                       (unsigned)i, (unsigned)i);
        }
    }

    if(changed != 0u)
    {
        svcrt_crash_commit();
    }
}

uint32 svcrt_crash_fault(uint32 slot, uint32 reason)
{
    svcrt_partition_table_t *p_pt = svcrt_ptable_get();
    svcrt_crash_journal_t *p_j = &svcrt_crash_journal;
    uint32 limit = svcrt_crash_limit();
    uint32 count;
    uint32 irq_state;

    if((slot >= p_pt->slot_max) || (slot >= (uint32)SVCRT_SLOT_ARRAY_MAX))
    {
        return 0u;
    }

    irq_state = SVCRT_ENTER_CRITICAL();

    /* RAM mirror first: this is what the shell and the host GUI read, and it
     * has to be right even for a slot that cannot be tagged (see below). */
    p_pt->slot_crash_cnt[slot]++;
    count = p_pt->slot_crash_cnt[slot];

    /* A slot with no pool address has no identity that would still mean
     * anything after a reset, so there is nothing honest to write down: the
     * RAM count stands, the journal stays untouched. */
    if(p_pt->slot_base[slot] != 0u)
    {
        if(p_j->base[slot] != p_pt->slot_base[slot])
        {
            /* The address changed under the entry (a re-install that reused the
             * record): the old count is not this image's, so it starts at 1. */
            svcrt_crash_clear_entry(slot);
            p_j->base[slot] = p_pt->slot_base[slot];
            p_j->crash_cnt[slot] = 0u;
        }

        p_j->crash_cnt[slot]++;
        p_j->last_reason[slot] = reason;

        if((limit != 0u) && (p_j->crash_cnt[slot] >= limit) &&
           (p_j->dis_reason[slot] == SVCRT_CRASH_REASON_NONE))
        {
            p_j->dis_reason[slot] = reason;
            p_j->dis_tick[slot]   = svcrt_kernel_tick;
        }

        svcrt_crash_commit();
    }

    SVCRT_EXIT_CRITICAL(irq_state);

    return count;
}

uint32 svcrt_crash_disabled(uint32 slot)
{
    const svcrt_partition_table_t *p_pt = svcrt_ptable_get();

    if((slot >= p_pt->slot_max) || (slot >= (uint32)SVCRT_SLOT_ARRAY_MAX))
    {
        return 0u;
    }

    return svcrt_crash_journal.dis_reason[slot];
}

uint32 svcrt_crash_disabled_tick(uint32 slot)
{
    const svcrt_partition_table_t *p_pt = svcrt_ptable_get();

    if((slot >= p_pt->slot_max) || (slot >= (uint32)SVCRT_SLOT_ARRAY_MAX))
    {
        return 0u;
    }

    return svcrt_crash_journal.dis_tick[slot];
}

uint32 svcrt_crash_count(uint32 slot)
{
    if(slot >= (uint32)SVCRT_SLOT_ARRAY_MAX)
    {
        return 0u;
    }

    return svcrt_crash_journal.crash_cnt[slot];
}

uint32 svcrt_crash_last_reason(uint32 slot)
{
    if(slot >= (uint32)SVCRT_SLOT_ARRAY_MAX)
    {
        return SVCRT_CRASH_REASON_NONE;
    }

    return svcrt_crash_journal.last_reason[slot];
}

void svcrt_crash_forget(uint32 slot)
{
    svcrt_partition_table_t *p_pt = svcrt_ptable_get();
    uint32 irq_state;

    if(slot >= (uint32)SVCRT_SLOT_ARRAY_MAX)
    {
        return;
    }

    irq_state = SVCRT_ENTER_CRITICAL();

    svcrt_crash_clear_entry(slot);

    if(slot < p_pt->slot_max)
    {
        p_pt->slot_crash_cnt[slot] = 0u;
    }

    svcrt_crash_commit();

    SVCRT_EXIT_CRITICAL(irq_state);
}

